    private void jButton15ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton15ActionPerformed
        try {
            double segundonum = Double.parseDouble(jTextField1.getText());
            double resultado = 0;

            switch(operacion){
                case "+" -> resultado = primernum + segundonum;
                case "-" -> resultado = primernum - segundonum;
                case "*" -> resultado = primernum * segundonum;
                case "/" -> {
                    if (segundonum == 0) {
                        jLabel3.setText("Error: División entre 0");
                        return;
                    }
                    resultado = primernum / segundonum;
                }
            }

            jLabel3.setText(String.valueOf(resultado));
            savememoria(resultado);
            jTextField1.setText("");

        } catch (Exception e) {
            jLabel3.setText("Hubo un error en la operación.");
        }
    }//GEN-LAST:event_jButton15ActionPerformed

