    //Método para guardar en memoria
    private void savememoria(double valor){
        if (pos < 10){
            numArreglo[pos] = valor;
            pos = pos + 1;
        }
        else{
            for (int i = 0; i < 9; i++){
                numArreglo[i] = numArreglo[i + 1];
            }
            numArreglo[9] = valor;
        }
    }

